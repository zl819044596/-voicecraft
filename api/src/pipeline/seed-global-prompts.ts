/**
 * 幂等 ensure：每个 type 仅当不存在全局默认（user_id IS NULL）时插入一条。
 * 已存在（含全局记录）一律跳过——不覆盖用户或已有全局内容。
 * 返回本次新插入条数（重启重跑应为 0）。
 */
export async function ensureGlobalPrompts(pg: DB): Promise<number> {
  let inserted = 0;
  for (const seed of GLOBAL_PROMPT_SEEDS) {
    try {
      const { rows } = await pg.query(
        `SELECT id FROM prompts WHERE type = $1 AND user_id IS NULL LIMIT 1`,
        [seed.type],
      );
      if (rows.length > 0) continue;
      await pg.query(
        `INSERT INTO prompts (user_id, type, name, scenario, body, tags, enabled, is_default)
         VALUES (NULL, $1, $2, NULL, $3, '{}', true, true)
         ON CONFLICT DO NOTHING`,
        [seed.type, seed.name, seed.body],
      );
      inserted += 1;
    } catch (err) {
      console.warn(`[seed] global prompt ${seed.type} skipped: ${(err as Error).message}`);
    }
  }
  if (inserted > 0) console.warn(`[seed] inserted ${inserted} global default prompt(s)`);
  return inserted;
}
